import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();

const THEME_CSS = "src/styles/modeless-theme.css";
const TAILWIND_CONFIG = "tailwind.config.ts";
const OUTPUT = "DESIGN.md";

/**
 * Variables in the theme that are not colors. Everything else in the :root
 * block resolves to an HSL triple and becomes a color token.
 */
const NON_COLOR_VARS = new Set([
  "--radius",
  "--angle-cut",
  "--font-display",
  "--font-ui",
  "--font-mono",
  "--motion-surface-opacity",
  "--artifact-frame-color",
]);

/** Typography levels, mirroring the utilities registered in tailwind.config.ts. */
const TYPOGRAPHY = [
  ["label", "--font-mono", "0.75rem", "1rem", "0.08em"],
  ["caption", "--font-ui", "0.8125rem", "1.25rem", null],
  ["micro", "--font-mono", "0.625rem", "0.875rem", "0.06em"],
  ["machine", "--font-mono", "0.6875rem", "1rem", "0.12em"],
];

/** Parse the `:root, .modeless-theme` block into raw declarations. */
async function readThemeBlock() {
  const css = await fs.readFile(path.join(root, THEME_CSS), "utf8");
  const block = css.match(/:root,\s*\.modeless-theme\s*\{([\s\S]*?)\n\}/);
  if (!block) throw new Error(`Could not find the :root block in ${THEME_CSS}.`);

  const declarations = new Map();
  for (const [, name, value] of block[1].matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    declarations.set(name, value.trim());
  }
  return declarations;
}

/**
 * Resolve `var(--x)` indirections to a literal value. The theme aliases
 * semantic roles onto core colors (`--primary: var(--acid-lime)`), so tokens
 * must be flattened before they can be emitted as DESIGN.md color values.
 */
function resolve(declarations, name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Circular variable reference at ${name}.`);
  seen.add(name);

  const value = declarations.get(name);
  if (!value) return null;

  const reference = value.match(/^var\((--[a-z0-9-]+)\)$/i);
  return reference ? resolve(declarations, reference[1], seen) : value;
}

/** "76 100% 58%" and "76 100% 58% / 0.08" are HSL components, not CSS colors. */
const isHslTriple = (value) => /^[\d.]+\s+[\d.]+%\s+[\d.]+%(\s*\/\s*[\d.]+)?$/.test(value);

const toCssColor = (value) => (isHslTriple(value) ? `hsl(${value})` : value);

const remToPx = (rem) => Number.parseFloat(rem) * 16;

function buildColors(declarations) {
  const colors = {};
  for (const name of declarations.keys()) {
    if (NON_COLOR_VARS.has(name)) continue;
    const resolved = resolve(declarations, name);
    if (!resolved || !isHslTriple(resolved)) continue;
    colors[name.replace(/^--/, "")] = toCssColor(resolved);
  }
  return colors;
}

function buildTypography(declarations) {
  const typography = {};
  for (const [level, familyVar, fontSize, lineHeight, letterSpacing] of TYPOGRAPHY) {
    typography[level] = {
      fontFamily: resolve(declarations, familyVar)?.split(",")[0].replace(/"/g, "").trim(),
      fontSize,
      fontWeight: 400,
      lineHeight,
      ...(letterSpacing ? { letterSpacing } : {}),
    };
  }
  return typography;
}

/**
 * Corner radii come from --radius plus the calc() steps in tailwind.config.ts.
 * DESIGN.md dimensions cannot hold calc(), so the arithmetic is resolved here.
 */
function buildRounded(declarations) {
  const base = remToPx(resolve(declarations, "--radius") ?? "0.375rem");
  return {
    sharp: "0px",
    panel: `${base - 2}px`,
    artifact: `${base}px`,
    soft: `${base + 4}px`,
  };
}

const yamlValue = (value) => (typeof value === "number" ? String(value) : `"${value}"`);

function toYaml(frontMatter) {
  const lines = [];
  for (const [section, contents] of Object.entries(frontMatter)) {
    if (typeof contents === "string") {
      lines.push(`${section}: ${yamlValue(contents)}`);
      continue;
    }
    if (Array.isArray(contents)) {
      lines.push(`${section}:`);
      for (const entry of contents) {
        lines.push(`  - section: ${entry.section}`);
        lines.push(`    reason: ${yamlValue(entry.reason)}`);
      }
      continue;
    }
    lines.push(`${section}:`);
    for (const [name, value] of Object.entries(contents)) {
      if (typeof value === "object") {
        lines.push(`  ${name}:`);
        for (const [property, propertyValue] of Object.entries(value)) {
          lines.push(`    ${property}: ${yamlValue(propertyValue)}`);
        }
      } else {
        lines.push(`  ${name}: ${yamlValue(value)}`);
      }
    }
  }
  return lines.join("\n");
}

function body(colors, declarations) {
  const fonts = {
    display: resolve(declarations, "--font-display"),
    ui: resolve(declarations, "--font-ui"),
    mono: resolve(declarations, "--font-mono"),
  };

  return `# Modeless Design System

<!-- Generated by scripts/generate-design-md.mjs from src/tokens and src/styles/modeless-theme.css. Do not edit by hand. -->

## Overview

Modeless is an interface language for AI-native product surfaces: agentic workflows, operational tooling, telemetry, and trust-sensitive systems. It reads as instrument panel rather than marketing page — dense, machine-adjacent, and quiet.

The system is dark by default. Bone text sits on near-black surfaces, and a single acid lime accent carries liveness. Motion behaves like slow telemetry rather than an alarm: long easing, low opacity change, organic drift, and no rapid flicker.

## Colors

The palette is a small set of core colors that semantic roles alias onto, so the same value can be re-pointed once and take effect everywhere.

- **Acid lime (${colors["acid-lime"]}):** liveness and active attention — processing, connected, selected, receiving updates. It is \`primary\`, \`signal\`, and \`ring\`.
- **Bone (${colors.bone}):** the default foreground, warmer and lower-glare than pure white.
- **Off-black (${colors["off-black"]}):** the page ground, with panel black and graphite as raised surfaces.
- **Completion green (${colors["completion-green"]}):** work that finished successfully and is now static.
- **Warning orange (${colors["warning-orange"]}):** recoverable issues, attention-required states, and destructive emphasis.
- **Electric purple (${colors["electric-purple"]}):** experimental surfaces and accents.

Acid lime marks liveness, never completion. A finished job rendered in lime reads as still running, so success uses completion green.

${
  Object.keys(colors).some((token) => token.startsWith("viz-"))
    ? "The `viz-*` tokens extend this into a controlled range for data visualization — structure, active, warning, risk, trust, and provenance families. Use one dominant structural hue, one active hue, and at most two secondary accents in a single component. Never rely on color alone.\n"
    : ""
}
## Typography

Three stacks carry the whole system:

- **Display** (${fonts.display?.split(",")[0]}): condensed and heavy, for headings set tight and uppercase.
- **UI** (${fonts.ui?.split(",")[0]}): the readable interface stack for body copy and controls.
- **Mono** (${fonts.mono?.split(",")[0]}): terminal output, metadata, and machine-adjacent labels.

The \`label\`, \`micro\`, and \`machine\` levels are uppercase with wide tracking and are for short interface text only. Body copy stays at 14px or larger with comfortable line height.

## Layout

The system has no spacing scale of its own. Layout uses the consuming app's spacing utilities directly, which is why the \`spacing\` section is omitted rather than empty.

Structure is carried by grid surfaces instead: thin, dotted, isometric, ASCII, and visualizer grids, plus a perspective variant. Animated grids hold the grid stationary and ripple a diffuse dark gravity wave across the surface roughly once per minute.

## Elevation & Depth

Depth is tonal, not shadowed. Surfaces step from off-black through panel black to graphite, separated by borders and grid lines rather than drop shadows. Scanline and noise overlays sit at low opacity to suggest a screen rather than paper.

## Shapes

The shape language is a 45-degree corner cut, not a radius. Cards and content sections use \`artifact-angle\`, which cuts the upper-left and lower-right corners by ${resolve(declarations, "--angle-cut")}. Background grids are deliberately exempt and stay square.

The \`rounded\` tokens below cover the small radii used by controls and inputs; they are secondary to the angle cut.

## Do's and Don'ts

- Do use acid lime for active and live states only.
- Do use completion green for finished work, so a static result does not read as still running.
- Do keep motion slow and telemetry-like, and let every animation respect \`prefers-reduced-motion\`.
- Do give icon-only controls an accessible name, and hide decorative glyphs from assistive technology.
- Don't use acid lime to indicate completion.
- Don't rely on color alone to carry state — pair it with text, shape, or structure.
- Don't apply the angle cut to page sections or background grids; it belongs on component surfaces.
- Don't use rapid flicker, strobing, jitter, or autoplay audio.

## Motion

Motion intensity is a public prop on motion-aware components, scaled \`off | subtle | live | high\`. Subtle is the default for cards, panels, and catalog surfaces; live suits hero graphics and primary visualizations; high is for controlled demos and should not ship as a production default.

Durations run from 120ms for instrument-like feedback to 60s for ambient gravity waves. These are not part of the DESIGN.md token schema and live in \`src/tokens/motion.ts\`.
`;
}

async function main() {
  const declarations = await readThemeBlock();
  const colors = buildColors(declarations);

  const frontMatter = {
    version: "alpha",
    name: "Modeless Design System",
    description: "Interface language for AI-native product surfaces: agentic workflows, operational tooling, and trust-sensitive systems.",
    omitted: [
      {
        section: "spacing",
        reason: "Modeless defines no spacing scale; layout uses the consuming app's spacing utilities.",
      },
      {
        section: "components",
        reason: "Component styling is expressed as Tailwind utilities and CVA variants in source. Per-component metadata is generated separately into the component registry.",
      },
    ],
    colors,
    typography: buildTypography(declarations),
    rounded: buildRounded(declarations),
  };

  const contents = `---\n${toYaml(frontMatter)}\n---\n\n${body(colors, declarations)}`;
  await fs.writeFile(path.join(root, OUTPUT), contents);

  console.log(
    `Generated ${OUTPUT}: ${Object.keys(colors).length} colors, ${Object.keys(frontMatter.typography).length} typography levels, ${Object.keys(frontMatter.rounded).length} rounded steps.`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}

export { TAILWIND_CONFIG, buildColors, buildRounded, readThemeBlock, resolve, toCssColor };
